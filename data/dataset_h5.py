"""
HDF5-backed dataset for TransRBP training on nohomo pre-split windows.

Expects HDF5 files generated by make_h5_nohomo.py:
    {h5_root}/{rbp}.h5
        {split}/inputs  (N, 5, 800)  float16
        {split}/labels  (N, 1, 800)  float16

The entire split is loaded into CPU RAM on __init__ as float32 tensors
(~175 MB per RBP split — fits comfortably on any GPU node).
DataLoader should use num_workers=0 since data is already in memory.
"""

import h5py
import torch
from torch.utils.data import Dataset


class RBPDataset(Dataset):

    def __init__(self, rbp, split='train', h5_path=None):
        if h5_path is None:
            raise ValueError('h5_path is required — pass the full path to {RBP}.h5')
        path = h5_path
        with h5py.File(path, 'r') as f:
            self.inputs = torch.from_numpy(
                f[f'{split}/inputs'][:].astype('float32'))
            self.labels = torch.from_numpy(
                f[f'{split}/labels'][:].astype('float32'))

        assert self.inputs.shape[-1] == 800, \
            f'Expected window length 800, got {self.inputs.shape[-1]}'

    def __len__(self):
        return len(self.inputs)

    def __getitem__(self, i):
        return self.inputs[i], self.labels[i]


